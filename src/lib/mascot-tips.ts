// Не повторяем последнюю подсказку в рамках одного и того же пула.
const lastByPool = new Map<string, string>();

export function pickTip(pathname: string): Tip {
  const key = "/" + pathname.replace(/^\/+/, "").replace(/\/+$/, "");
  const routeTips = ROUTE_TIPS[key] ?? ROUTE_TIPS["/"];
  const useFact = Math.random() < 0.3;
  const poolKey = useFact ? "__facts__" : key;
  const pool = useFact ? FARM_FACTS : routeTips;

  let tip = pool[Math.floor(Math.random() * pool.length)];
  const last = lastByPool.get(poolKey);
  if (tip.text === last && pool.length > 1) {
    const idx = pool.indexOf(tip);
    tip = pool[(idx + 1) % pool.length];
  }
  lastByPool.set(poolKey, tip.text);
  return tip;
}
